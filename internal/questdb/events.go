package questdb

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/TylerAkins/forever-quest-markers/internal/questiepolicy"
)

// EventSchedule is the runtime policy generated for holiday and war-effort
// pins. Quest IDs map to Questie event names; event names map to year-less
// windows or to a disabled marker.
type EventSchedule struct {
	ByQuest    map[int]string
	Events     map[string]questiepolicy.EventWindow
	Overrides  map[int]questiepolicy.EventWindow
	Lunar      map[int]questiepolicy.EventWindow
	LunarFirst int
	LunarLast  int
	Disabled   map[string]bool
	WarEffort  map[int]bool
}

// BuildEventSchedule reconciles Questie's holiday data with the generated quest
// records. It fails when a yearly record has no event name or a referenced event
// has neither a window nor a disabled marker.
func BuildEventSchedule(policy *questiepolicy.Policy, records []Record) (*EventSchedule, error) {
	schedule := &EventSchedule{
		ByQuest:   map[int]string{},
		Events:    map[string]questiepolicy.EventWindow{},
		Overrides: map[int]questiepolicy.EventWindow{},
		Lunar:     map[int]questiepolicy.EventWindow{},
		Disabled:  map[string]bool{},
		WarEffort: map[int]bool{},
	}
	for _, record := range records {
		if !record.IsYearly {
			continue
		}
		eventName := policy.HolidayNames[record.QuestID]
		if eventName == "" {
			return nil, fmt.Errorf("quest %d is yearly but has no Questie holiday name", record.QuestID)
		}
		schedule.ByQuest[record.QuestID] = eventName
		if window, ok := policy.EventOverrides[record.QuestID]; ok {
			schedule.Overrides[record.QuestID] = window
		}
	}
	usesLunar := false
	for questID, eventName := range schedule.ByQuest {
		if policy.DisabledEvents[eventName] {
			schedule.Disabled[eventName] = true
			continue
		}
		// Questie skips Darkmoon Faire on Forever and has no faire window we can
		// import. Most DMF records also mix Mulgore and Elwynn coordinates, so a
		// date-only gate would pin both grounds.
		if eventName == "Darkmoon Faire" {
			schedule.Disabled[eventName] = true
			continue
		}
		if eventName == "Lunar Festival" {
			usesLunar = true
			continue
		}
		window, ok := policy.EventWindows[eventName]
		if !ok {
			return nil, fmt.Errorf("quest %d event %q has no Questie date window", questID, eventName)
		}
		schedule.Events[eventName] = window
	}
	if usesLunar {
		if len(policy.LunarWindows) == 0 {
			return nil, fmt.Errorf("Lunar Festival quests have no Questie year table")
		}
		for year, window := range policy.LunarWindows {
			schedule.Lunar[year] = window
		}
		schedule.LunarFirst = policy.LunarYearFirst
		schedule.LunarLast = policy.LunarYearLast
	}
	for questID := range policy.WarEffortQuestIDs {
		schedule.WarEffort[questID] = true
	}
	return schedule, nil
}

func renderEventPolicy(schedule *EventSchedule, meta Metadata) []byte {
	var builder strings.Builder
	builder.WriteString("-- AUTO-GENERATED FILE\n")
	builder.WriteString("-- DO NOT EDIT MANUALLY\n")
	builder.WriteString("-- Source: Questie/Questie Holiday event dates and AQWarEffortQuests\n")
	if meta.PolicyCommit != "" {
		builder.WriteString("-- Policy commit: " + meta.PolicyCommit + "\n")
	}
	builder.WriteString("-- Generated by cmd/fqp build-db\n")
	builder.WriteString("--\n")
	builder.WriteString("-- Event windows use Questie's year-less { month, day, hour, minute } tuples.\n")
	builder.WriteString("-- A window whose start sorts after its end crosses New Year.\n\n")
	builder.WriteString("local ADDON_NAME, ns = ...\n")
	builder.WriteString("ns.EventPolicy = {\n")

	builder.WriteString("\tbyQuest = {\n")
	for _, questID := range sortedStringKeys(schedule.ByQuest) {
		builder.WriteString("\t\t[")
		builder.WriteString(strconv.Itoa(questID))
		builder.WriteString("] = ")
		builder.WriteString(quoteLua(schedule.ByQuest[questID]))
		builder.WriteString(",\n")
	}
	builder.WriteString("\t},\n")

	builder.WriteString("\tevents = {\n")
	for _, eventName := range sortedWindowKeys(schedule.Events) {
		window := schedule.Events[eventName]
		builder.WriteString("\t\t[")
		builder.WriteString(quoteLua(eventName))
		builder.WriteString("] = ")
		builder.WriteString(renderWindow(window))
		builder.WriteString(", -- ")
		builder.WriteString(describeWindow(window))
		builder.WriteString("\n")
	}
	builder.WriteString("\t},\n")

	builder.WriteString("\toverrides = {\n")
	for _, questID := range sortedWindowKeys(schedule.Overrides) {
		window := schedule.Overrides[questID]
		builder.WriteString("\t\t[")
		builder.WriteString(strconv.Itoa(questID))
		builder.WriteString("] = ")
		builder.WriteString(renderWindow(window))
		builder.WriteString(", -- ")
		builder.WriteString(describeWindow(window))
		builder.WriteString("\n")
	}
	builder.WriteString("\t},\n")

	builder.WriteString("\tlunar = {\n")
	for _, year := range sortedYearKeys(schedule.Lunar) {
		window := schedule.Lunar[year]
		builder.WriteString("\t\t[")
		builder.WriteString(strconv.Itoa(year))
		builder.WriteString("] = ")
		builder.WriteString(renderWindow(window))
		builder.WriteString(", -- ")
		builder.WriteString(describeWindow(window))
		builder.WriteString("\n")
	}
	builder.WriteString("\t},\n")

	builder.WriteString("\tlunarYears = { first = ")
	builder.WriteString(strconv.Itoa(schedule.LunarFirst))
	builder.WriteString(", last = ")
	builder.WriteString(strconv.Itoa(schedule.LunarLast))
	builder.WriteString(" },\n")

	builder.WriteString("\tdisabled = {\n")
	for _, eventName := range sortedBoolKeys(schedule.Disabled) {
		builder.WriteString("\t\t[")
		builder.WriteString(quoteLua(eventName))
		builder.WriteString("] = true,\n")
	}
	builder.WriteString("\t},\n")

	builder.WriteString("\twarEffort = {\n")
	for _, questID := range sortedIntKeys(schedule.WarEffort) {
		builder.WriteString("\t\t[")
		builder.WriteString(strconv.Itoa(questID))
		builder.WriteString("] = true,\n")
	}
	builder.WriteString("\t},\n")
	builder.WriteString("}\n")
	return []byte(builder.String())
}

func renderWindow(window questiepolicy.EventWindow) string {
	return fmt.Sprintf("{ { %d, %d, %d, %d }, { %d, %d, %d, %d } }",
		window.Start.Month, window.Start.Day, window.Start.Hour, window.Start.Minute,
		window.End.Month, window.End.Day, window.End.Hour, window.End.Minute)
}

var eventMonthNames = [...]string{"", "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"}

func describeWindow(window questiepolicy.EventWindow) string {
	monthName := func(month int) string {
		if month < 1 || month > 12 {
			return "?"
		}
		return eventMonthNames[month]
	}
	return fmt.Sprintf("%d %s %02d:%02d to %d %s %02d:%02d",
		window.Start.Day, monthName(window.Start.Month), window.Start.Hour, window.Start.Minute,
		window.End.Day, monthName(window.End.Month), window.End.Hour, window.End.Minute)
}

func sortedStringKeys(values map[int]string) []int {
	keys := make([]int, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Ints(keys)
	return keys
}

func sortedWindowKeys[K string | int](values map[K]questiepolicy.EventWindow) []K {
	keys := make([]K, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	return keys
}

func sortedYearKeys(values map[int]questiepolicy.EventWindow) []int {
	return sortedWindowKeys(values)
}

func sortedBoolKeys(values map[string]bool) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func sortedIntKeys(values map[int]bool) []int {
	keys := make([]int, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Ints(keys)
	return keys
}
