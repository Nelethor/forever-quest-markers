package release

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

var newsHeading = regexp.MustCompile(`^## (\d+\.\d+\.\d+)\s*-`)
var newsCount = regexp.MustCompile(`^Ship \d+ quests with \d+ coordinate pins`)

// RenderNews keeps the latest player-facing release independent of data-only updates.
func RenderNews(changelog string) (string, error) {
	version := ""
	var entries []string
	finish := func() string {
		if version == "" || len(entries) == 0 {
			return ""
		}
		var b strings.Builder
		b.WriteString("-- Generated by go run ./cmd/fqp generate-news from CHANGELOG.md.\nlocal _, ns = ...\nns.WhatsNew = {\n    version = ")
		b.WriteString(strconv.Quote(version))
		b.WriteString(",\n    lines = {\n")
		for _, entry := range entries {
			entry = strings.ReplaceAll(strings.ReplaceAll(entry, "`", ""), "**", "")
			b.WriteString("        " + strconv.Quote(entry) + ",\n")
		}
		b.WriteString("    },\n}\n")
		return b.String()
	}
	for _, line := range strings.Split(changelog, "\n") {
		if heading := newsHeading.FindStringSubmatch(line); heading != nil {
			if result := finish(); result != "" {
				return result, nil
			}
			version, entries = heading[1], nil
		} else if version != "" && strings.HasPrefix(line, "- ") {
			entry := strings.TrimPrefix(line, "- ")
			if !strings.HasPrefix(entry, "Update the QuestieDB Forever artifact ") && !newsCount.MatchString(entry) {
				entries = append(entries, entry)
			}
		}
	}
	if result := finish(); result != "" {
		return result, nil
	}
	return "", fmt.Errorf("no player-facing changelog entry found")
}

func GenerateNews(root string) error {
	contents, err := os.ReadFile(filepath.Join(root, "CHANGELOG.md"))
	if err != nil {
		return err
	}
	news, err := RenderNews(string(contents))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, "WhatsNew.lua"), []byte(news), 0644)
}
